package com.localkeep.core.model

import java.io.File
import java.time.Instant
import java.util.UUID
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

/**
 * A committed schema-5 payload, and the two things a rollback plan needs to be true about it.
 *
 * The rollback for this feature is a *forward* build with `MakeInvisibleAvailability` off — never an
 * older APK — and the reason is exactly what this file pins. Once schema 5 is on disk it carries
 * lease pairs and a reveal-phrase verifier that a schema-4 build does not know about. Protobuf drops
 * unknown fields silently, so an older build that agreed to open this payload would decode it minus
 * the leases, write the truncated version back, and every concealed entry in the vault would become
 * an ordinary visible one — permanently, with nothing red anywhere. The version gate is the only
 * thing standing between a downgrade and that, so it gets a fixture rather than a unit test over a
 * value built in memory.
 *
 * The bytes are regenerated by [regenerateFixture] and committed. Never regenerate one to make a
 * failing test pass: a fixture whose job is "this is what the shipped format looked like" is worth
 * exactly as much as its refusal to change.
 */
class Schema5HiddenFixtureTest {

    private val fixture: File
        get() {
            var dir: File? = File(System.getProperty("user.dir")).absoluteFile
            while (dir != null && !File(dir, "settings.gradle.kts").isFile) dir = dir.parentFile
            val root = requireNotNull(dir) { "could not locate the repository root" }
            return File(root, "core/model/src/test/resources/vectors/vault-v5-hidden.bin")
        }

    @Test
    fun theGeneratorStillProducesExactlyTheCommittedBytes() {
        // Keeps [regenerateFixture] alive and honest in one assertion. A generator nothing calls is
        // dead code that rots until the day someone needs it; a generator that silently drifts from
        // the committed bytes turns "regenerate the fixture" into "quietly change what shipped".
        val rebuilt = File.createTempFile("vault-v5-hidden", ".bin").also { it.deleteOnExit() }
        regenerateFixture(rebuilt)
        assertContentEquals(fixture.readBytes(), rebuilt.readBytes())
    }

    @Test
    fun theFixtureDecodesAtSchemaFiveWithEveryKindOfHiddenRecordIntact() {
        val vault = VaultSerializer.decode(fixture.readBytes())

        assertEquals(5, vault.schemaVersion)
        assertNotNull(vault.revealPhrase, "a schema-5 vault that has ever hidden anything carries a verifier")

        val live = vault.items.single { it.title == "Offshore account" }
        val trashed = vault.items.single { it.title == "Old statement" }
        val folder = vault.folders.single { it.name == "Offshore" }

        assertEquals(FAR_FUTURE, live.hiddenUntil, "direct-hidden live item")
        assertEquals(STAMP, live.hiddenUpdatedAt)
        assertEquals(FAR_FUTURE, trashed.hiddenUntil, "direct-hidden trashed item")
        assertNotNull(trashed.deletedAt)
        assertEquals(FAR_FUTURE, folder.hiddenUntil, "direct-hidden folder")
        assertEquals(STAMP, folder.hiddenUpdatedAt)

        // The verifier's own bytes survive, not merely its presence. A verifier that decoded with a
        // zeroed salt or hash would still be non-null and would reject every correct phrase — which
        // presents to the user as "my reveal phrase stopped working", the failure mode with the
        // fewest clues in it.
        val verifier = assertNotNull(vault.revealPhrase)
        assertContentEquals(SALT, verifier.salt)
        assertContentEquals(HASH, verifier.hash)
        assertEquals(19, verifier.iterations)
    }

    @Test
    fun reEncodingTheFixtureChangesNothingButTheVersionStamp() {
        // Was `reproducesItByteForByte`, asserting a fixed point through `encode`. That held only
        // while 5 *was* current: from schema 6 the fixture is an older vault, and opening an older
        // vault upgrades it — which is the documented behaviour and what makes the downgrade
        // refusal below honest, not a regression.
        //
        // The claim worth keeping is the one that was really being made: a save the emergency build
        // performs rewrites nothing it did not change. So the payload past the version varint must
        // still be identical, and the stamp must have moved to current — every lease and the
        // verifier carried through untouched.
        val bytes = fixture.readBytes()
        val resaved = VaultSerializer.encode(VaultSerializer.decode(bytes))

        assertContentEquals(byteArrayOf(0x08, 0x05), bytes.copyOf(2))
        assertContentEquals(
            byteArrayOf(0x08, Vault.CURRENT_SCHEMA_VERSION.toByte()),
            resaved.copyOf(2),
        )
        assertContentEquals(bytes.drop(2).toByteArray(), resaved.drop(2).toByteArray())
    }

    @Test
    fun savingAndReopeningPreservesEveryLease() {
        val reopened = VaultSerializer.decode(VaultSerializer.encode(VaultSerializer.decode(fixture.readBytes())))

        assertTrue(reopened.items.all { it.hiddenUntil == null || it.hiddenUntil == FAR_FUTURE })
        assertEquals(2, reopened.items.count { it.hiddenUntil != null })
        assertEquals(1, reopened.folders.count { it.hiddenUntil != null })
    }

    @Test
    fun aFrozenSchemaFourDecoderRefusesTheFixture() {
        // The real schema-4 build is not on this classpath, so the gate is reproduced rather than
        // imported: `decode`'s upper bound with the constant frozen at 4. That is honest about what
        // is being tested — the *rule*, not the old binary — and it fails the moment someone
        // "fixes" a downgrade complaint by widening the bound instead of shipping forward.
        val bytes = fixture.readBytes()
        val declared = VaultSerializer.decode(bytes).schemaVersion
        assertFailsWith<IllegalArgumentException> {
            require(declared <= FROZEN_SCHEMA_4_MAX) {
                "This vault was created by a newer version of LocalKeep (format $declared; " +
                    "this build understands up to $FROZEN_SCHEMA_4_MAX). Update the app to open it."
            }
        }
    }

    @Test
    fun aPayloadOneVersionAheadIsRefusedByThisBuildForTheSameReason() {
        // The symmetric half: today's build must refuse tomorrow's format rather than truncating it.
        // Named for the relationship rather than for a number — it was `aSchemaSixPayload...` and
        // schema 6 has since shipped, so the name described the current format instead of the next
        // one while the assertion below (CURRENT + 1) went on being right.
        val ahead = VaultSerializer.encodeAtVersion(
            VaultSerializer.decode(fixture.readBytes()),
            Vault.CURRENT_SCHEMA_VERSION + 1,
        )
        assertFailsWith<IllegalArgumentException> { VaultSerializer.decode(ahead) }
    }

    companion object {
        private val STAMP: Instant = Instant.parse("2026-08-18T12:00:00Z")
        private val FAR_FUTURE: Instant = Instant.parse("2099-01-01T00:00:00Z")
        private const val FROZEN_SCHEMA_4_MAX = 4
        private val SALT = ByteArray(16) { (it + 1).toByte() }
        private val HASH = ByteArray(32) { (0xA0 + it).toByte() }

        /**
         * Rebuilds `vault-v5-hidden.bin`. Point it at the committed path only when schema 5's
         * *shipped* shape genuinely changes, which after release it cannot.
         *
         * Every id, instant and byte here is fixed, so the output is reproducible.
         */
        @JvmStatic
        fun regenerateFixture(target: File) {
            val folderId = UUID.fromString("00000000-0000-4000-8000-00000000f01d")
            val vault = Vault(
                items = listOf(
                    VaultItem(
                        id = UUID.fromString("00000000-0000-4000-8000-000000000001"),
                        title = "Offshore account",
                        createdAt = STAMP,
                        updatedAt = STAMP,
                        content = Note("statement"),
                        hiddenUntil = FAR_FUTURE,
                        hiddenUpdatedAt = STAMP,
                    ),
                    VaultItem(
                        id = UUID.fromString("00000000-0000-4000-8000-000000000002"),
                        title = "Old statement",
                        createdAt = STAMP,
                        updatedAt = STAMP,
                        deletedAt = STAMP,
                        content = Note("archived"),
                        hiddenUntil = FAR_FUTURE,
                        hiddenUpdatedAt = STAMP,
                    ),
                    VaultItem(
                        id = UUID.fromString("00000000-0000-4000-8000-000000000003"),
                        title = "Cafe wifi",
                        createdAt = STAMP,
                        updatedAt = STAMP,
                        folderId = folderId,
                        content = Note("guest"),
                    ),
                ),
                folders = listOf(
                    Folder(
                        id = folderId,
                        name = "Offshore",
                        updatedAt = STAMP,
                        hiddenUntil = FAR_FUTURE,
                        hiddenUpdatedAt = STAMP,
                    ),
                ),
                createdAt = STAMP,
                modifiedAt = STAMP,
                revealPhrase = RevealPhraseVerifier(
                    salt = SALT,
                    memoryKib = 65536,
                    iterations = 19,
                    parallelism = 1,
                    hash = HASH,
                ),
            )
            target.parentFile.mkdirs()
            // encodeAtVersion(5), not encode(). This fixture's whole value is that it is a payload
            // as schema 5 shipped it, and `encode` stamps whatever the current version is — so on
            // the day schema 6 landed the generator started producing a schema-6 payload and two
            // tests failed with a byte diff at index 1. The version is part of what is being
            // frozen, so it is named here rather than inherited.
            target.writeBytes(VaultSerializer.encodeAtVersion(vault, 5))
        }
    }
}
